// Generates src/engine/sim/historyData.ts from data/history/us-annual.csv (the attributed source).
const text = await Bun.file(new URL('../data/history/us-annual.csv', import.meta.url)).text()
const rows = text
  .split('\n')
  .filter((l) => l && !l.startsWith('#') && !l.startsWith('year'))
  .map((l) => l.split(',').map(Number))
const header = text
  .split('\n')
  .filter((l) => l.startsWith('#'))
  .map((l) => `//${l.slice(1)}`)
  .join('\n')
const out = `// Generated by scripts/genHistory.ts from data/history/us-annual.csv — do not edit.
${header}
// Columns: year, S&P 500 total return, 3-month T-bill, 10-year Treasury, CPI-U Dec/Dec.
export const HISTORY: readonly (readonly [number, number, number, number, number])[] = ${JSON.stringify(rows)}
`
await Bun.write(new URL('../src/engine/sim/historyData.ts', import.meta.url), out)
console.log(`wrote ${rows.length} years`)
